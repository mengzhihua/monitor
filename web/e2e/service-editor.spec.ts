import { expect, test } from '@playwright/test'

test('service editor validates, persists and preserves drafts across conflicts', async ({ page, request }) => {
  const headers = { Authorization: 'Bearer browser-test-token' }
  let initial = await (await request.get('/api/v1/services/config', { headers })).json()
  expect((await request.put('/api/v1/services/config', { headers, data: { revision: initial.revision, services: [] } })).ok()).toBe(true)
  await page.goto('/?view=services&token=browser-test-token')
  await page.getByRole('button', { name: '配置服务树', exact: true }).click()
  const editor = page.getByRole('region', { name: '服务配置编辑' })
  await editor.getByRole('button', { name: '添加服务' }).click()
  await editor.getByLabel('服务名称 1', { exact: true }).fill('checkout')
  await editor.getByLabel('依赖服务 1', { exact: true }).fill('missing')
  await editor.getByRole('button', { name: '校验并预览' }).click()
  await expect(editor.getByRole('alert')).toContainText('does not exist')
  await expect(editor.getByRole('button', { name: '保存服务配置' })).toBeDisabled()
  await editor.getByLabel('依赖服务 1', { exact: true }).fill('')
  await editor.getByLabel('关联告警 1', { exact: true }).fill('one, two')
  await editor.getByRole('button', { name: '校验并预览' }).click()
  await expect(editor.locator('.preview')).toContainText('校验通过')
  initial = await (await request.get('/api/v1/services/config', { headers })).json()
  expect(initial.services).toEqual([])
  expect((await request.put('/api/v1/services/config', { headers, data: { revision: initial.revision, services: [{ name: 'other-operator' }] } })).ok()).toBe(true)
  await editor.getByRole('button', { name: '保存服务配置' }).click()
  await expect(editor.getByRole('alert')).toContainText('草稿已保留')
  await expect(editor.getByLabel('服务名称 1', { exact: true })).toHaveValue('checkout')
  await editor.getByRole('button', { name: '读取最新版本并保留草稿' }).click()
  await expect(editor).toContainText('将移除：other-operator')
  await expect(editor.getByRole('button', { name: '保存服务配置' })).toBeDisabled()
  await editor.getByRole('button', { name: '校验并预览' }).click()
  await expect(editor.locator('.preview')).toContainText('two')
  await editor.getByRole('button', { name: '保存服务配置' }).click()
  await expect(editor).toContainText('服务配置已保存并生效')
  await expect(page.locator('[data-service="checkout"]')).toBeVisible()
  const saved = await (await request.get('/api/v1/services/config', { headers })).json()
  expect(saved.services).toEqual([{ name: 'checkout', alarms: ['one', 'two'] }])
  await page.reload()
  await expect(page.locator('[data-service="checkout"]')).toBeVisible()
  await page.getByRole('button', { name: '配置服务树', exact: true }).click()
  await editor.getByLabel('服务名称 1', { exact: true }).fill('unsaved')
  page.once('dialog', dialog => dialog.dismiss())
  await editor.getByRole('button', { name: '关闭编辑' }).click()
  await expect(editor.getByLabel('服务名称 1', { exact: true })).toHaveValue('unsaved')
})

test('reader has no service editing actions', async ({ page }) => {
  await page.goto('/?view=services&token=browser-viewer-token')
  await expect(page.locator('.services h1')).toBeVisible()
  await expect(page.getByRole('button', { name: '配置服务树', exact: true })).toHaveCount(0)
})
