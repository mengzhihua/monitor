import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { openTools } from './mobile-navigation'

test('registered host workspace opens from monitoring and handles real files', async ({ page }, info) => {
  await page.goto('/?view=charts&token=browser-admin-token')
  await openTools(page)
  await page.getByTitle('主机文件管理').click()
  const shortcuts = page.getByRole('region', { name: '桌面快捷方式' })
  await expect(shortcuts).toBeVisible()
  await page.screenshot({ path: info.outputPath('desktop.png') })
  await shortcuts.getByRole('button', { name: '主机信息' }).click()
  await expect(page.locator('.host-info')).toContainText('browser-test')
  if (info.project.name === 'desktop') {
    await page.getByRole('button', { name: '还原窗口' }).click()
    const titlebar = page.locator('.titlebar h2')
    const bounds = (await titlebar.boundingBox())!
    await page.mouse.move(bounds.x+35, bounds.y+10)
    await page.mouse.down()
    await page.mouse.move(bounds.x+65, bounds.y+33)
    await page.mouse.up()
    expect((await titlebar.boundingBox())!.x).toBeGreaterThan(bounds.x)
    await page.getByRole('button', { name: '最大化窗口' }).click()
  }
  await page.getByRole('button', {name:'最小化窗口'}).click()
  await shortcuts.getByRole('button', {name:'我的电脑'}).click()
  await expect(page.getByRole('heading', { name: '我的电脑' })).toBeVisible()
  await page.locator('.item.host').filter({ hasText: 'browser-test' }).click()
  await page.getByRole('button', { name: '新建文件夹' }).click()
  const directory = info.project.name + '-files'
  await page.getByRole('textbox', { name: '名称' }).fill(directory)
  await page.getByRole('button', { name: '确定', exact: true }).click()
  await page.locator('.item').filter({ hasText: directory }).click()
  await page.getByRole('button', { name: '打开 ' + directory }).click()
  await expect(page.getByRole('button', { name: '上传', exact: true })).toBeEnabled()
  await page.getByRole('button', {name:'最小化窗口'}).click()
  await shortcuts.getByRole('button', {name:'最近位置'}).click()
  await page.getByRole('button', {name:new RegExp(directory)}).click()
  await expect(page.getByRole('heading', {name:directory})).toBeVisible()
  await page.getByRole('button', {name:'最小化窗口'}).click()
  await page.locator('.taskbar').getByRole('button', {name:'文件管理'}).click()
  await expect(page.getByRole('heading', {name:directory})).toBeVisible()
  await expect(page.getByRole('button', { name: '上传', exact: true })).toBeEnabled()
  const input = page.locator('.explorer input[type=file]')
  await input.setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('主机文件内容') })
  const note = page.locator('.item').filter({ hasText: 'notes.txt' })
  await note.click()
  await page.getByRole('button', { name: '打开 notes.txt' }).click()
  await expect(page.locator('dialog pre')).toHaveText('主机文件内容')
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('button', { name: '重命名' }).click()
  await page.getByRole('textbox', { name: '名称' }).fill('renamed.txt')
  await page.getByRole('button', { name: '确定', exact: true }).click()
  await expect(page.locator('.item').filter({ hasText: 'renamed.txt' })).toBeVisible()
  const buffer = Buffer.alloc(700000, 123)
  await input.setInputFiles({ name: 'sample.bin', mimeType: 'application/octet-stream', buffer })
  await page.locator('.item').filter({ hasText: 'sample.bin' }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载', exact: true }).click()
  expect(buffer.equals(await readFile((await (await download).path())!))).toBe(true)
  await page.getByRole('button', { name: '列表视图' }).click()
  await page.getByRole('button', { name: '详情', exact: true }).click()
  await page.screenshot({path:info.outputPath('host-files.png')})
  await page.getByRole('button', { name: '删除', exact: true }).click()
  await page.getByRole('button', { name: '确认删除' }).click()
  await expect(page.locator('.item').filter({ hasText: 'sample.bin' })).toHaveCount(0)
  await page.getByRole('button', { name: '返回监控' }).filter({visible:true}).click()
  await expect(page.locator('.metrics-workspace')).toBeVisible()
})
